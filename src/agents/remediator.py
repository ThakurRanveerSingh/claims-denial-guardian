@dataclass
class RemediationAttempt:
    attempt_number: int
    sql: str
    validation: ValidationResult
    # None when `validation.success` is False -- the fresh-build pass never
    # runs if the cheaper populated-db pass already failed (no point
    # spending the extra work). Both must succeed for the attempt to count.
    fresh_build: Optional[FreshBuildResult] = None


@dataclass
class RemediatorResult:
    incident_id: str
    status: str  # "success" | "failed_validation" | "no_fix_available"
    fix_target: Optional[FixTarget] = None
    attempts: list = field(default_factory=list)  # list[RemediationAttempt]
    pr_url: Optional[str] = None
    pr_already_existed: bool = False
    pr_updated: bool = False  # True only when force=True regenerated an already-open PR in place
    branch_name: Optional[str] = None
    owner: Optional[str] = None
    reason: Optional[str] = None  # human-readable reason for failed/no_fix_available


# ---------------------------------------------------------------------------
# MCP reads (schema + ownership) -- same session-spawning pattern as
# investigator.py/scribe.py, duplicated deliberately (decision 0007's
# Consequences section already states why this codebase doesn't share this
# boilerplate across agent modules).
# ---------------------------------------------------------------------------


async def _call_mcp_tool(session: ClientSession, tool_name: str, arguments: dict) -> dict:
    result = await session.call_tool(tool_name, arguments)
    parts = []
    for block in result.content:
        text = getattr(block, "text", None)
        parts.append(text if text is not None else str(block))
    return json.loads("\n".join(parts))


async def _resolve_entity_urn(session: ClientSession, table_name: str) -> Optional[str]:
    data = await _call_mcp_tool(session, "search", {"query": f"/q {table_name}", "filter": "entity_type = dataset", "num_results": 20})
    for result in data.get("searchResults", []):
        entity = result.get("entity", {})
        if entity.get("properties", {}).get("name") == table_name:
            return entity.get("urn")
    return None


async def _get_entity_details(session: ClientSession, urn: str) -> dict:
    return await _call_mcp_tool(session, "get_entities", {"urns": urn})


def _schema_fields(details: dict) -> list:
    fields = (details.get("schemaMetadata") or {}).get("fields") or []
    return [(f.get("fieldPath"), f.get("nativeDataType")) for f in fields]


def _first_owner_name(details: dict) -> Optional[str]:
    owners = (details.get("ownership") or {}).get("owners") or []
    if not owners:
        return None
    return owners[0].get("owner", {}).get("name")


async def _fetch_schema_and_owner_async(fix_target: FixTarget) -> tuple:
    """Returns (schema_context: dict[table_name, list[(field, type)]], owner: Optional[str]).
    Live MCP reads for the target table and every upstream table it names
    — the prompt handed to the LLM uses ONLY what comes back here, never
    an assumed column list."""
    server_params = StdioServerParameters(
        command="uvx", args=["mcp-server-datahub@latest"],
        env={**os.environ, "DATAHUB_GMS_URL": DATAHUB_SERVER, "DATAHUB_GMS_TOKEN": DATAHUB_TOKEN or ""},
    )
    schema_context = {}
    owner = None
    async with stdio_client(server_params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            for table_name in (fix_target.table_name,) + fix_target.upstream_tables:
                urn = await _resolve_entity_urn(session, table_name)
                if urn is None:
                    continue
                details = await _get_entity_details(session, urn)
                schema_context[table_name] = _schema_fields(details)
                if table_name == fix_target.table_name:
                    owner = _first_owner_name(details)
    return schema_context, owner


def fetch_schema_and_owner(fix_target: FixTarget) -> tuple:
    return asyncio.run(_fetch_schema_and_owner_async(fix_target))


# ---------------------------------------------------------------------------
# Prompt construction and SQL extraction.
# ---------------------------------------------------------------------------


_FENCED_SQL_RE = re.compile(r"```sql\s*(.*?)\s*```", re.DOTALL)


def _extract_sql(text: str) -> str:
    """Pull the LAST fenced ```sql``` block out of the model's response --
    same "last, not first" reasoning as investigator.py's
    _extract_fenced_json (a model that second-guesses itself mid-answer
    may show an earlier draft before its real final answer). Raises
    ValueError if none found, which the retry loop turns into an
    honest failed attempt, not a crash.
    """
    matches = _FENCED_SQL_RE.findall(text or "")
    if not matches:
        raise ValueError("no fenced ```sql``` block found in the model's response")
    return matches[-1].strip()


def _format_schema(schema_context: dict) -> str:
    lines = []
    for table_name, fields in schema_context.items():
        lines.append(f"{table_name}:")
        for field_path, native_type in fields:
            lines.append(f"  {field_path} {native_type}")
    return "\n".join(lines)


def _build_fix_prompt(
    finding, fix_target: FixTarget, current_sql: str, schema_context: dict,
    *, previous_sql: Optional[str] = None, previous_error: Optional[str] = None,
) -> str:
    lines = [
        "You are Remediator, an agent that generates a fix SQL script for a data-quality",
        "defect an investigation has already found and explained.",
        "",
        f"Investigator's finding: {finding.primary_root_cause}",
        f"Root cause summary: {finding.root_cause_summary}",
        "",
        "Live, current schema (read from DataHub, not assumed):",
        _format_schema(schema_context),
        "",
        f"Current build SQL for `{fix_target.table_name}` (from the pipeline-owner's own repo):",
        "```sql",
        current_sql.strip(),
        "```",
        "",
        "Task: rewrite this into a fix SQL script that QUARANTINES rows",
        f"violating `{fix_target.check_column} >= 0` instead of letting them land in",
        f"`{fix_target.table_name}` unexamined. Do NOT correct or alter any values",
        "(e.g. do not use ABS() or flip a sign) -- the cause of the violation is not",
        "established well enough to assume a correction is safe. Requirements:",
        "",
        f"1. Build a `{fix_target.table_name}_quarantine` table (same columns as",
        f"   `{fix_target.table_name}`) containing exactly the rows that violate",
        f"   `{fix_target.check_column} >= 0` (or are NULL/unparseable, if the column is",
        "   text -- treat anything that cannot be evaluated as >= 0 as a violation too),",
        "   using the SAME upstream source(s) and derivation logic as the current build",
        "   SQL above.",
        f"2. Rebuild `{fix_target.table_name}` itself with only the clean rows, using that",
        "   SAME upstream derivation.",
        "3. This file will be validated TWICE: once against a database that already has",
        f"   real data in `{fix_target.table_name}` (does the fix clean it correctly?), and",
        "   once against a COMPLETELY FRESH, EMPTY database that has never had",
        f"   `{fix_target.table_name}` or `{fix_target.table_name}_quarantine` created at all",
        "   (does this file still work as a from-scratch build script, the same job the",
        "   ORIGINAL file above did?). Both must pass. This means:",
        "   - Do NOT DROP the table to rebuild it. Some tables in this database have other",
        "     SQL VIEWS defined against them elsewhere; a DROP + CREATE-replacement + RENAME",
        "     sequence leaves those views unable to resolve the table for a moment",
        "     mid-script and fails the whole script, even though the end state would have",
        "     been fine.",
        "   - Do NOT assume the table already exists either (e.g. a bare `DELETE FROM",
        f"     {fix_target.table_name}` with no CREATE anywhere fails outright on a fresh",
        "     database).",
        "   - The pattern that satisfies both constraints at once: `CREATE TABLE IF NOT",
        "     EXISTS` the table using a `SELECT ... WHERE 0` (a real SQLite idiom -- this",
        "     creates the correct columns with zero rows if the table doesn't exist yet,",
        "     and does nothing at all if it already does), THEN `DELETE FROM` it and",
        "     `INSERT INTO` it with the real, filtered rows. Worked example for a table",
        "     `t` built from `SELECT cols FROM upstream`:",
        "     ```sql",
        "     CREATE TABLE IF NOT EXISTS t AS SELECT cols FROM upstream WHERE 0;",
        "     DELETE FROM t;",
        "     INSERT INTO t SELECT cols FROM upstream WHERE <clean condition>;",
        "     ```",
        "     Apply this SAME pattern to BOTH the quarantine table and the main table.",
        "4. Every row implied by the original derivation must end up in EXACTLY ONE of",
        f"   the two places (`{fix_target.table_name}` or `{fix_target.table_name}_quarantine`)",
        "   -- nothing dropped, nothing duplicated.",
        "5. Keep the ORIGINAL file's header comment (the lineage/design-rationale notes",
        "   shown at the top of the current build SQL above) -- APPEND your own comment",
        "   explaining the quarantine fix underneath it, do not delete or replace it. A",
        "   future engineer reading this file still needs to know WHY the original design",
        "   choices were made, not just what this fix changed.",
        "",
        "Respond with ONLY one fenced ```sql``` code block containing the complete,",
        "runnable SQL script (may be multiple statements) -- no prose outside the block.",
    ]
    if previous_sql:
        lines += [
            "",
            "Your previous attempt failed. Previous SQL:",
            "```sql",
            previous_sql,
            "```",
            f"Failure reason: {previous_error}",
            "Fix the issue and try again.",
        ]
    elif previous_error is not None:
        # Extraction itself failed last time (no fenced ```sql``` block found,
        # or the backend call errored) -- there is no previous SQL worth
        # showing, only the reason to avoid repeating it.
        lines += [
            "",
            f"Your previous attempt failed before producing usable SQL: {previous_error}",
            "Make sure your response contains exactly one fenced ```sql``` code block.",
        ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Retry loop.
# ---------------------------------------------------------------------------


def _generate_and_validate(
    backend: LLMBackend, finding, fix_target: FixTarget, current_sql: str, schema_context: dict,
    healthcare_db_path: Path, data_platform_repo_path: Path, max_retries: int = DEFAULT_MAX_RETRIES,
) -> tuple:
    """Returns (attempts: list[RemediationAttempt], final_success: bool).
    An attempt only counts as success when BOTH validation passes succeed
    -- see the module docstring for why a single pass (correct-on-top-of-
    already-populated-data) isn't the same question as "would I merge this
    file," and missed exactly that during Part D's own live run."""
    attempts = []
    previous_sql, previous_error = None, None

    for attempt_num in range(1, max_retries + 2):  # 1, 2, 3 for max_retries=2
        prompt = _build_fix_prompt(
            finding, fix_target, current_sql, schema_context,
            previous_sql=previous_sql, previous_error=previous_error,
        )
        try:
            completion = backend.complete([{"role": "user", "content": prompt}], max_tokens=4096, timeout_s=GENERATION_TIMEOUT_S)
            sql = _extract_sql(completion.text)
        except (LLMBackendError, ValueError) as e:
            validation = ValidationResult(success=False, original_count=0, error=str(e))
            attempts.append(RemediationAttempt(attempt_number=attempt_num, sql="", validation=validation))
            previous_sql, previous_error = "", str(e)
            continue

        with scratch_copy(healthcare_db_path) as scratch_path:
            validation = apply_and_validate_fix(
                scratch_path, sql,
                original_table=fix_target.table_name, clean_table=fix_target.table_name,
                quarantine_table=f"{fix_target.table_name}_quarantine", check_column=fix_target.check_column,
            )

        if not validation.success:
            attempts.append(RemediationAttempt(attempt_number=attempt_num, sql=sql, validation=validation))
            previous_sql = sql
            previous_error = validation.error or (
                f"validation failed: {validation.violation_count_in_clean} rows still violate "
                f"the check in the clean table, or conservation failed "
                f"(clean={validation.clean_count}, quarantine={validation.quarantine_count}, "
                f"original={validation.original_count})"
            )
            continue

        # Pass 1 succeeded -- now the harder question: does this file still
        # work as a from-scratch build, not just on top of data pass 1's
        # own scratch copy already had?
        with fresh_scratch_db() as fresh_path:
            seed_fresh_raw_patients(fresh_path, healthcare_db_path)
            fresh_build = run_fresh_build(
                fresh_path, fix_target.table_name, sql, data_platform_repo_path, check_column=fix_target.check_column,
            )

        attempts.append(RemediationAttempt(attempt_number=attempt_num, sql=sql, validation=validation, fresh_build=fresh_build))

        if fresh_build.success:
            return attempts, True

        previous_sql = sql
        if fresh_build.failed_stage is not None:
            previous_error = (
                f"fresh-database build failed at the '{fresh_build.failed_stage}' stage "
                f"(this file must still work as a from-scratch build, not just against a "
                f"database that already has data in it): {fresh_build.error}"
            )
        else:
            previous_error = (
                f"the fix ran on a fresh database without a SQL error, but "
                f"{fresh_build.violation_count_in_clean} rows still violate the check in "
                f"the clean table -- the fresh-database branch of this script is producing "
                f"different results than intended"
            )

    return attempts, False


