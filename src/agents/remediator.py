def run_remediator(
    incident, backend: LLMBackend, *,
    healthcare_db_path: Path = DB_PATH, data_platform_repo_path: Path = DATA_PLATFORM_REPO_PATH, force: bool = False,
) -> RemediatorResult:
    """Top-level entry point, matching sentinel.py/investigator.py/
    scribe.py's run_<agent>() naming convention. `incident` is an
    Incident (src/agents/orchestrator.py) with a confident (non-inconclusive)
    InvestigatorFinding — callers check this before calling, same as
    Scribe's own "nothing to do" short-circuit.

    Idempotency check happens HERE, before any LLM call or DataHub read —
    not only inside _open_pr. A branch name is a pure function of
    incident_id alone (_branch_name_for), so "does a PR already exist for
    this incident" can be answered before fix_target, schema, or a single
    token of generation is needed. Checking only inside _open_pr (an
    earlier version of this function did exactly that) would still have
    prevented a duplicate PR, but would keep paying for a real LLM call and
    live DataHub reads on every rerun — the actual expensive part of a
    repeat run, not the git/PR mechanics.

    `force`: skip that short-circuit and regenerate even when a PR already
    exists, pushing the update onto the SAME branch (_open_pr's own
    `force=` path) rather than opening a second PR for the same incident.
    For the one real, deliberate reason this exists: the fix criteria
    itself changed (e.g. fresh_build_validation.py was added after the
    first PRs already existed) and an already-open PR needs to be redone,
    not silently left stale.
    """
    finding = incident.investigator
    if finding is None or finding.primary_root_cause == "inconclusive":
        return RemediatorResult(incident_id=incident.incident_id, status="no_fix_available", reason="no confident InvestigatorFinding to remediate")

    fix_target = _fix_target_for(finding.primary_root_cause)
    if fix_target is None:
        return RemediatorResult(incident_id=incident.incident_id, status="no_fix_available", reason=f"no known fix shape for primary_root_cause={finding.primary_root_cause!r}")

    branch_name = _branch_name_for(incident.incident_id)
    existing_pr_url = _existing_pr_url(branch_name)
    if existing_pr_url and not force:
        return RemediatorResult(
            incident_id=incident.incident_id, status="success", fix_target=fix_target,
            pr_url=existing_pr_url, pr_already_existed=True, branch_name=branch_name,
        )

    # A PREVIOUS run's _open_pr() may have left the working tree checked
    # out on some other incident's guardian/fix-* branch (git checkout -B
    # switches it and never switches back). run_fresh_build (inside
    # _generate_and_validate below) reads the OTHER 3 transform files
    # straight off disk, not via git -- resetting to origin/main here,
    # before any file read happens, guarantees every stage's "real,
    # unmodified" content is actually main's, not whatever a prior branch
    # happened to leave checked out. _read_committed_file for the fix's
    # OWN file is already immune to this (reads the git blob directly),
    # but the other 3 files aren't, so the working tree itself needs to be
    # put in a known-good state too.
    _run_git(["fetch", "origin", "main"], cwd=data_platform_repo_path)
    checkout_main = _run_git(["checkout", "-B", "main", "origin/main"], cwd=data_platform_repo_path)
    if checkout_main.returncode != 0:
        raise RuntimeError(f"git checkout -B main origin/main failed: {checkout_main.stderr}")

    current_sql = _read_committed_file(data_platform_repo_path, fix_target.transform_file)
    schema_context, owner = fetch_schema_and_owner(fix_target)

    attempts, success = _generate_and_validate(
        backend, finding, fix_target, current_sql, schema_context, healthcare_db_path, data_platform_repo_path,
    )

    if not success:
        return RemediatorResult(
            incident_id=incident.incident_id, status="failed_validation", fix_target=fix_target,
            attempts=attempts, owner=owner,
            reason=f"all {len(attempts)} attempt(s) failed validation",
        )

    final_attempt = attempts[-1]
    title = _pr_title(finding.primary_root_cause, incident.incident_id)
    body = _build_pr_body(
        incident.incident_id, incident.sentinel, finding, fix_target,
        final_attempt.sql, final_attempt.validation, final_attempt.fresh_build, owner,
    )

    pr_url, already_existed, updated = _open_pr(fix_target, final_attempt.sql, title, body, incident.incident_id, branch_name, force=force)

    return RemediatorResult(
        incident_id=incident.incident_id, status="success", fix_target=fix_target,
        attempts=attempts, pr_url=pr_url, pr_already_existed=already_existed, pr_updated=updated,
        branch_name=branch_name, owner=owner,
    )
