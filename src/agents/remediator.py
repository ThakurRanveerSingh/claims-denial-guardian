#!/usr/bin/env python3
"""
Remediator — generates a fix for what Investigator found, validates it
deterministically, and opens a real pull request (US-3). Design:
docs/decisions/0008-remediator-design.md. Read that file for the full
reasoning — this module implements it, not re-derives it.

The core judgment call this module embodies, stated plainly (the repo
owner's own words, worth repeating here rather than only in the design
doc): **quarantine suspect rows, never silently correct them.** The
tempting fix for a sign-flip is `ABS(billing_amount)` — negatives become
positive, the anomaly disappears, the demo looks clean. Rejected: we don't
actually know *why* the flip happened, and in health insurance, silently
"fixing" financial data you don't understand is exactly how a data team
creates the next wrongful-denial incident while erasing the evidence of
this one. A dead-letter quarantine table says: clean rows flow, suspect
rows get surfaced for a human, nothing is invented. Same evidence
discipline as Investigator refusing to assume a root cause it hasn't
verified — Guardian never pretends to know more than the evidence
supports.

Two fix shapes, chosen by `InvestigatorFinding.primary_root_cause`, both
applied to the SAME simulated pipeline-owner repo
(~/projects/denial-guardian-data-platform) but at different files:

  - `introduced_at:X` — the defect first appears at X's own build. Fix
    modifies X's transform file directly (e.g. transform/claims.sql):
    split the build into a clean table and an `X_quarantine` table.
  - `inherited_from:X` — the defect is already present in the earliest
    available data (X, e.g. raw_patients), which this simulated team
    doesn't own and can't fix. Fix instead modifies the FIRST transform
    stage this team DOES own downstream of X (transform/staging_patients.sql)
    — the same split pattern, one hop later, because the real source can't
    be touched.

LLM usage is single-shot generation (`LLMBackend.complete()`), not a
multi-turn agentic loop — a real, structural difference from Investigator,
not an oversight: there's no exploration needed, just "given this real
schema and this finding, generate SQL," checked deterministically
afterward. No Design A/B split needed; `complete()` already works
uniformly across all three backends from Sprint 2.

Validation is 100% deterministic — SQL generated by the model, checked by
code, never by re-asking the model. TWO separate, required passes, added
after Part D's own live run surfaced why one pass isn't enough:

  1. src/codegen/sql_validation.py — runs the candidate SQL against a
     scratch COPY of the real, already-populated healthcare.db, never the
     committed one (Sprint 3 WP1 Part A's own lesson, learned the hard
     way). Answers "does this fix clean the data correctly?"
  2. src/codegen/fresh_build_validation.py — runs the ENTIRE transform
     sequence (staging_patients -> mart_billing -> mart_demographics ->
     claims) against a database seeded with NOTHING but a small real
     raw_patients sample, with the candidate SQL standing in for its one
     stage. Answers a different question a human reviewer actually asks
     before merging a file: "does this file still do everything the old
     file did?" Part D's first live Cigna fix passed pass 1 cleanly while
     silently dropping its own CREATE TABLE statement — the generated file
     could no longer bootstrap on a genuinely fresh database, and pass 1
     had no way to see that, because every db it ever tests against
     already has the table. Fresh-database runnability was a real
     invariant nobody had written down as a check, so nothing guarded it.
     This is the general shape of most escaped bugs: not wrong answers to
     asked questions, but unasked ones.

Both passes must succeed for an attempt to count. Up to 2 retries with the
exact error from whichever pass failed fed back; after that, an honest
failure, no PR.

PR body is a deterministic template built from Incident/InvestigatorFinding
fields — the ONE place free-form model text appears is a single, clearly
marked section quoting `root_cause_summary` verbatim. No fresh LLM prose
writes the PR description itself.
"""

