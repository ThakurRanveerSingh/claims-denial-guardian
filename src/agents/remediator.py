@dataclass(frozen=True)
class FixTarget:
    """Which file gets modified, which table it builds, and what upstream
    schema context the model needs to see. One of these per
    primary_root_cause prefix -- see _fix_target_for()."""

    transform_file: str      # relative to DATA_PLATFORM_REPO_PATH, e.g. "transform/claims.sql"
    table_name: str          # the table this transform builds, e.g. "claims"
    upstream_tables: tuple   # table names the transform reads FROM, for schema context
    check_column: str = "billing_amount"


FIX_TARGET_CLAIMS = FixTarget(
    transform_file="transform/claims.sql", table_name="claims",
    upstream_tables=("mart_billing", "mart_demographics"),
)
FIX_TARGET_STAGING = FixTarget(
    transform_file="transform/staging_patients.sql", table_name="staging_patients",
    upstream_tables=("raw_patients",),
)


def _fix_target_for(primary_root_cause: str) -> Optional[FixTarget]:
    """`introduced_at:X` -> fix X's own build. `inherited_from:X` -> X
    isn't ours to fix (it's upstream, e.g. raw_patients), so fix the first
    transform stage THIS simulated team owns downstream of it instead —
    staging_patients, not X itself. Returns None for "inconclusive" or any
    other value: there's no fix to generate for a finding with no
    confident root cause.
    """
    if primary_root_cause.startswith("introduced_at:"):
        return FIX_TARGET_CLAIMS
    if primary_root_cause.startswith("inherited_from:"):
        return FIX_TARGET_STAGING
    return None


def _pr_title(primary_root_cause: str, incident_id: str) -> str:
    """Distinct, legible-at-a-glance titles per fix shape (repo owner's
    explicit ask, Part B amendment 2) -- a formatting decision keyed off
    primary_root_cause, not new machinery."""
    if primary_root_cause.startswith("introduced_at:"):
        return f"Guard claims build: quarantine sign-flipped billing ({incident_id})"
    if primary_root_cause.startswith("inherited_from:"):
        return f"Quarantine invalid source billing at staging boundary ({incident_id})"
    return f"Guardian fix ({incident_id})"


