def _branch_name_for(incident_id: str) -> str:
    return f"guardian/fix-{incident_id.lower()}"


def _incident_github_url(incident_id: str) -> str:
    return f"https://github.com/{MAIN_REPO_GITHUB_SLUG}/blob/main/examples/{incident_id}/incident.json"


def _build_pr_body(
    incident_id: str, sentinel_finding, finding, fix_target: FixTarget, sql: str,
    validation: ValidationResult, fresh_build: Optional[FreshBuildResult], owner: Optional[str],
) -> str:
    segment = sentinel_finding.segment
    conservation = "PASS" if validation.conserves_rows else "FAIL"
    owner_line = owner or "unknown — not found in DataHub ownership metadata"
    fresh_build_line = "PASS" if (fresh_build is not None and fresh_build.success) else "not run"

    return f"""## Guardian-generated fix

**Incident**: `{incident_id}`
**Segment**: {segment.insurance_provider} / {segment.medical_condition} (z = {sentinel_finding.z_score:.2f})
**Root cause**: `{finding.primary_root_cause}`
**Confidence**: {finding.confidence}

## What changed

`{fix_target.transform_file}` now splits rows at build time: clean rows
(`{fix_target.check_column} >= 0`) continue to `{fix_target.table_name}` as
before; violating rows are routed to a new
`{fix_target.table_name}_quarantine` table instead of silently landing in
`{fix_target.table_name}`.

## Why quarantine, not correction

The tempting fix here would be to correct the values directly (e.g.
`ABS({fix_target.check_column})`) and make the anomaly disappear. This PR
does not do that: **we don't actually know the cause of the violation, and
in health insurance, silently "fixing" financial data you don't understand
is exactly how a data team creates the next wrongful-denial incident while
erasing the evidence of this one.** Clean rows flow, suspect rows are
routed to `{fix_target.table_name}_quarantine` for a human to review,
nothing is invented. Guardian never pretends to know more than the
evidence supports.

## Validation (deterministic, two required passes — never the real database)

Pass 1 — does the fix clean the data correctly? (scratch COPY of the real,
already-populated healthcare.db)

| Check | Result |
|---|---|
| Original `{fix_target.table_name}` row count | {validation.original_count} |
| Clean rows after fix | {validation.clean_count} |
| **Quarantined rows** | **{validation.quarantine_count}** |
| Violations remaining in clean table (must be 0) | {validation.violation_count_in_clean} |
| Conservation (clean + quarantined == original) | {conservation} |

Pass 2 — does this file still work as a from-scratch build script, the
same job the original file did? (a genuinely fresh database, seeded with
nothing but a small real `raw_patients` sample, run through the ENTIRE
transform sequence)

| Check | Result |
|---|---|
| Fresh-database build | {fresh_build_line} |

## Operational note

Rows in `{fix_target.table_name}_quarantine` require human review — suggested
owner: **{owner_line}** (read live from DataHub ownership metadata).

## Investigator's Finding (verbatim)

> {finding.root_cause_summary}

## Generated fix SQL

```sql
{sql}
```

Full incident record: {_incident_github_url(incident_id)}
"""


def _run_git(args: list, cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(["git"] + args, cwd=str(cwd), capture_output=True, text=True, timeout=30)


def _existing_pr_url(branch_name: str) -> Optional[str]:
    """Deliberately does NOT use `gh ... --jq '.[0].url'`: jq's `.[0]` on an
    empty JSON array evaluates to `null`, and `.url` on `null` is also
    `null` — jq's default text output for that is the 4-character string
    `"null"`, not empty stdout. A naive `.strip() or None` on that would
    read as "an existing PR was found" (truthy non-empty string) when
    there genuinely isn't one, breaking idempotency in exactly the case it
    exists to handle. Parsing the JSON array directly sidesteps that
    footgun entirely.
    """
    result = subprocess.run(
        ["gh", "pr", "list", "--repo", DATA_PLATFORM_REPO_SLUG, "--head", branch_name, "--json", "url"],
        capture_output=True, text=True, timeout=30,
    )
    if result.returncode != 0:
        return None
    try:
        prs = json.loads(result.stdout or "[]")
    except json.JSONDecodeError:
        return None
    return prs[0]["url"] if prs else None


def _read_committed_file(repo_path: Path, relative_file: str, ref: str = "origin/main") -> str:
    """Read a file's content as committed on `ref`, NOT from the local
    working tree. `_open_pr` leaves the working tree checked out on
    whichever branch it last created/updated (`git checkout -B`) — reading
    straight off disk risks showing the model a stale or already-fixed
    version of the file instead of the true current original, depending on
    what an earlier run happened to leave checked out. `git show` reads
    the committed blob directly and is unaffected by the working tree's
    current state."""
    result = subprocess.run(
        ["git", "show", f"{ref}:{relative_file}"], cwd=str(repo_path), capture_output=True, text=True, timeout=10,
    )
    if result.returncode != 0:
        raise RuntimeError(f"failed to read {relative_file} from {ref}: {result.stderr}")
    return result.stdout


def _open_pr(fix_target: FixTarget, sql: str, title: str, body: str, incident_id: str, branch_name: str, *, force: bool = False) -> tuple:
    """Returns (pr_url, already_existed, updated). Takes `branch_name` from
    the caller rather than recomputing it, since run_remediator() already
    checked it for an existing PR before ever generating anything — this
    function's own check (below) is defense-in-depth against a race (e.g.
    two runs overlapping), not the primary idempotency guard; see
    run_remediator()'s docstring for why the primary check had to move
    earlier than this function.

    `force`: when an existing PR is found AND force=True, push an updated
    commit onto that SAME branch (advancing it, not rewriting it) and
    `gh pr edit` its title/body, instead of short-circuiting. Used when the
    fix criteria itself changed (e.g. a new validation pass was added) and
    an already-open PR needs to be regenerated in place, not left stale
    and not duplicated into a second PR for the same incident.
    """
    existing = _existing_pr_url(branch_name)
    if existing and not force:
        return existing, True, False

    repo = DATA_PLATFORM_REPO_PATH
    _run_git(["fetch", "origin", "main"], cwd=repo)

    if existing and force:
        # Advance the EXISTING branch with a new commit on top, not a
        # rebuild off main -- a plain new commit is the less disruptive way
        # to update a PR a reviewer may already be looking at, versus
        # rewriting history underneath them.
        _run_git(["fetch", "origin", branch_name], cwd=repo)
        checkout = _run_git(["checkout", "-B", branch_name, f"origin/{branch_name}"], cwd=repo)
    else:
        checkout = _run_git(["checkout", "-B", branch_name, "origin/main"], cwd=repo)
    if checkout.returncode != 0:
        raise RuntimeError(f"git checkout -B {branch_name} failed: {checkout.stderr}")

    target_path = repo / fix_target.transform_file
    target_path.write_text(sql.rstrip() + "\n")

    _run_git(["add", fix_target.transform_file], cwd=repo)
    commit_subject = f"Update fix: {title}" if (existing and force) else title
    commit = _run_git(
        ["commit", "-m", f"{commit_subject}\n\nGenerated by Guardian's Remediator. See PR body for validation results."], cwd=repo,
    )
    if commit.returncode != 0:
        raise RuntimeError(f"git commit failed: {commit.stderr}")

    push = _run_git(["push", "-u", "origin", branch_name, "--force-with-lease"], cwd=repo)
    if push.returncode != 0:
        # --force-with-lease fails cleanly if the remote branch doesn't
        # exist yet (nothing to lease against), OR if it does exist but the
        # local ref just fetched isn't its current tip for some reason --
        # retry a plain push once.
        push = _run_git(["push", "-u", "origin", branch_name], cwd=repo)
        if push.returncode != 0:
            raise RuntimeError(f"git push failed: {push.stderr}")

    if existing and force:
        edit_result = subprocess.run(
            ["gh", "pr", "edit", existing, "--repo", DATA_PLATFORM_REPO_SLUG, "--title", title, "--body", body],
            capture_output=True, text=True, timeout=60,
        )
        if edit_result.returncode != 0:
            raise RuntimeError(f"gh pr edit failed: {edit_result.stderr}")
        return existing, True, True

    pr_result = subprocess.run(
        ["gh", "pr", "create", "--repo", DATA_PLATFORM_REPO_SLUG, "--title", title, "--body", body, "--head", branch_name, "--base", "main"],
        capture_output=True, text=True, timeout=60,
    )
    if pr_result.returncode != 0:
        raise RuntimeError(f"gh pr create failed: {pr_result.stderr}")

    pr_url = pr_result.stdout.strip().splitlines()[-1] if pr_result.stdout.strip() else None
    if not pr_url:
        raise RuntimeError(f"gh pr create produced no URL. stdout={pr_result.stdout!r}")
    return pr_url, False, False


